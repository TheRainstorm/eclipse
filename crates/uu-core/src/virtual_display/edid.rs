//! Per-definition EDID identity. The original signed driver reads this data
//! through its supported CustomEdid setting; no driver binary is modified.
use sha2::{Digest, Sha256};
use uuid::Uuid;

fn descriptor(block: &mut [u8], kind: u8, text: &str) {
    block.fill(0);
    block[3] = kind;
    block[5..].fill(b' ');
    let ascii: Vec<_> = text
        .bytes()
        .filter(|b| b.is_ascii_graphic() || *b == b' ')
        .take(13)
        .collect();
    block[5..5 + ascii.len()].copy_from_slice(&ascii);
    if ascii.len() < 13 {
        block[5 + ascii.len()] = b'\n';
    }
}
