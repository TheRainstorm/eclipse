#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn names_change_without_changing_identity_and_both_blocks_are_valid() {
        let id = Uuid::new_v4();
        let first = monitor(id, "Athena Luna");
        let renamed = monitor(id, "Apollo Vega");
        assert_eq!(&first[12..16], &renamed[12..16]);
        assert_ne!(
            &first[12..16],
            &monitor(Uuid::new_v4(), "Athena Luna")[12..16]
        );
        assert_eq!(&first[113..125], b"Athena Luna\n");
        for data in [first, renamed, monitor(id, "非常长的自定义显示器名称")] {
            for block in data.chunks_exact(128) {
                assert_eq!(block.iter().fold(0u8, |sum, b| sum.wrapping_add(*b)), 0);
            }
        }
    }
}
