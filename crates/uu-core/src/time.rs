//! Wall-clock timestamps for diagnostics and control protocols.
/// Current UNIX time in milliseconds (the outer Message field 2).
pub fn now_ms() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_millis() as u64)
        .unwrap_or(0)
}
