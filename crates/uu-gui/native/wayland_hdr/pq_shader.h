static const char pq_frag[]=
"uniform sampler2D scene;\n"
"uniform float reference_white;\n"
"out vec4 result;\n"
"vec3 inv_srgb(vec3 encoded) {\n"
"    vec3 v = abs(encoded);\n"
"    vec3 lin = mix(v / 12.92, pow((v + 0.055) / 1.055, vec3(2.4)),\n"
"                   greaterThan(v, vec3(0.04045)));\n"
"    return sign(encoded) * lin;\n"
"}\n"
"vec3 to_pq(vec3 nits) {\n"
"    vec3 p = pow(clamp(nits / 10000.0, 0.0, 1.0), vec3(2610.0 / 16384.0));\n"
"    return pow((3424.0/4096.0 + 2413.0/128.0*p) / (1.0 + 2392.0/128.0*p),\n"
"               vec3(2523.0/32.0));\n"
"}\n"
"void main() {\n"
"    // GBM row zero is the top of the Wayland buffer.\n"
"    ivec2 pixel = ivec2(gl_FragCoord.xy);\n"
"    pixel.y = textureSize(scene, 0).y - 1 - pixel.y;\n"
"    vec3 linear_709 = inv_srgb(texelFetch(scene, pixel, 0).rgb);\n"
"    // Preserve negative intermediate Rec.709 components until they are back in Rec.2020.\n"
"    vec3 wide = vec3(dot(linear_709, vec3(0.627404,0.329283,0.043313)),\n"
"                     dot(linear_709, vec3(0.069097,0.919540,0.011362)),\n"
"                     dot(linear_709, vec3(0.016391,0.088013,0.895595)));\n"
"    vec3 pq = to_pq(wide * reference_white);\n"
"    // The target's AR30 framebuffer provides the DRM channel layout.\n"
"    result = vec4(pq.rgb, 1.0);\n"
"}\n"
;
